export function currencyForCountryIso(iso: string | null | undefined): string | null {
  if (!iso) return null;
  return COUNTRY_CURRENCY[iso.trim().toUpperCase()] ?? null;
}

export function resolveSignupCurrency(
  countryIso: string | null | undefined,
  submitted?: string | null,
): string {
  return currencyForCountryIso(countryIso) ?? (submitted ? submitted.toUpperCase() : "");
}
