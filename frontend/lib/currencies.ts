const CURRENCY_CODES = new Set(CURRENCIES.map((currency) => currency.code));

export function isSupportedCurrency(code: string | undefined | null): boolean {
  return !!code && CURRENCY_CODES.has(code.toUpperCase());
}

export function currencySymbol(code: string | null | undefined): string {
  const upper = (code ?? "").toUpperCase();
  return CURRENCIES.find((row) => row.code === upper)?.symbol || upper || "";
}

